package xyz.mooma0750.wave.core.music

/** YouTube（www.youtube.com）の動画のページから読んだ、新作の確かめに使う値。 */
data class VideoFacts(
    /** 説明文（配信元から来た曲は「Provided to YouTube by …」で始まる自動の説明文）。 */
    val description: String?,
    val viewCount: Long?,
    /** 公開日（`2026/07/27` など、表示のまま）。 */
    val publishedText: String?,
)

/** 自動の説明文（Provided to YouTube by …）の中身。 */
data class ReleaseCredits(
    val label: String?,
    /** 2段目の「題名 · アーティスト · …」のアーティストと、Main Artist の欄。 */
    val artists: List<String>,
    /** Lyricist・Composer・Writer の欄。 */
    val writers: List<String>,
    /** Released on の日付（`2026-07-28`）。 */
    val releasedOn: String?,
)

/**
 * 新作の出元が怪しいかの判定（印を付けて残す。外さない）。
 * 第三者が有名アーティストの名前で無関係の曲を配信し、YouTube がそのアーティストのページにまとめることがある（2026-11 の HoneyWorks の
 * 「Echoes for Peace」。名義は「HoneyWorks OFFICIAL」、作詞・作曲も同じ名義、公開から3か月で再生3回）。
 * 本物でもレーベルは作品ごとにばらばら（タイアップ・コラボ）なので、レーベルの違いでは判定しない。
 */
object ReleaseSuspicion {
    /** 名義がアーティスト名に「公式」などを足しただけのもの（なりすまし）。 */
    const val NAME = "name"

    /** 作詞・作曲が、アーティスト名に何かを足した名義そのまま（個人の名前が無い。ボカロ曲・タイアップで作曲者が名義に並ぶのは除く）。 */
    const val WRITER = "writer"

    /** 公開から日が経っているのに、ほとんど再生されていない。 */
    const val VIEWS = "views"

    private const val MIN_VIEWS = 100
    private const val VIEWS_GRACE_DAYS = 14
    private val NAME_SUFFIXES = setOf("official", "公式", "officialchannel", "channel")

    fun credits(description: String?): ReleaseCredits? {
        val text = description?.trim() ?: return null
        val label = text.lineSequence().firstOrNull()?.removePrefix("Provided to YouTube by ")?.takeIf { text.startsWith("Provided to YouTube by ") }?.trim()
        if (label == null && !text.contains("Auto-generated by YouTube.")) return null
        val paragraphs = text.split("\n\n").map { it.trim() }
        val artists = mutableListOf<String>()
        // 2段目は「題名 · アーティスト · アーティスト」
        paragraphs.getOrNull(1)?.split(" · ")?.drop(1)?.map { it.trim() }?.filter { it.isNotEmpty() }?.let { artists += it }
        val writers = mutableListOf<String>()
        var releasedOn: String? = null
        for (line in text.lines()) {
            val colon = line.indexOf(": ")
            if (colon <= 0) continue
            val keys = line.substring(0, colon).split(",").map { it.trim() }
            val value = line.substring(colon + 2).trim()
            if (value.isEmpty()) continue
            when {
                keys == listOf("Released on") -> releasedOn = value
                keys.any { it == "Main Artist" } -> artists += value
            }
            if (keys.any { it == "Lyricist" || it == "Composer" || it == "Writer" }) writers += value
        }
        return ReleaseCredits(label, artists.distinct(), writers.distinct(), releasedOn)
    }

    /** 怪しい点（無ければ空）。artistName はアーティストのページの名前。 */
    fun reasons(
        artistName: String,
        facts: VideoFacts,
        nowEpochMs: Long,
    ): List<String> {
        val page = key(artistName)
        val credits = credits(facts.description)
        val reasons = mutableListOf<String>()
        if (credits != null) {
            val names = credits.artists.map(::key)
            if (names.any { it != page && it.startsWith(page) && it.removePrefix(page) in NAME_SUFFIXES }) reasons += NAME
            val writers = credits.writers.map(::key)
            if (writers.isNotEmpty() && writers.all { it in names && it != page && page in it }) reasons += WRITER
        }
        val released = epochDay(credits?.releasedOn) ?: epochDay(facts.publishedText)
        val views = facts.viewCount
        if (views != null && views < MIN_VIEWS && released != null && nowEpochMs / DAY_MS - released >= VIEWS_GRACE_DAYS) reasons += VIEWS
        return reasons
    }

    /** 照らす形（大文字・小文字・全角・半角・空白を区別しない）。 */
    private fun key(name: String) = TextFold.fold(name).filterNot { it.isWhitespace() }

    private const val DAY_MS = 24L * 60 * 60 * 1000
    private val DATE = Regex("""(\d{4})[-/](\d{1,2})[-/](\d{1,2})""")

    /** `2026-07-28`・`2026/07/27` の、1970-01-01 からの日数。 */
    internal fun epochDay(text: String?): Long? {
        val m = DATE.find(text ?: return null) ?: return null
        val (y0, mo, d) = m.destructured.toList().map { it.toLong() }
        // 暦の日付から日数へ（Howard Hinnant の days_from_civil）
        val y = if (mo <= 2) y0 - 1 else y0
        val era = (if (y >= 0) y else y - 399) / 400
        val yoe = y - era * 400
        val doy = (153 * (mo + (if (mo > 2) -3 else 9)) + 2) / 5 + d - 1
        val doe = yoe * 365 + yoe / 4 - yoe / 100 + doy
        return era * 146097 + doe - 719468
    }
}

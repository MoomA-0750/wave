package xyz.mooma0750.wave.core.music

import xyz.mooma0750.wave.core.Fixtures
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNull

class ReleaseSuspicionTest {
    /** 2026-11-02 の時刻。 */
    private val now = (ReleaseSuspicion.epochDay("2026-11-02")!!) * 24 * 60 * 60 * 1000

    @Test
    fun aReleaseUnderAFakeNameIsMarked() {
        // HoneyWorks のページに混ざった別人の曲（名義は HoneyWorks OFFICIAL、作詞・作曲も同じ名義、3か月で再生3回）
        val facts = MusicParsers.videoFacts(Fixtures.json("video_facts_suspect"))
        assertEquals(3, facts.viewCount)
        val credits = ReleaseSuspicion.credits(facts.description)!!
        assertEquals("B-Komachi", credits.label)
        assertEquals(listOf("HoneyWorks OFFICIAL", "Han Shika"), credits.artists)
        assertEquals(listOf("HoneyWorks OFFICIAL"), credits.writers)
        assertEquals("2026-07-28", credits.releasedOn)
        assertEquals(listOf(ReleaseSuspicion.NAME, ReleaseSuspicion.WRITER, ReleaseSuspicion.VIEWS), ReleaseSuspicion.reasons("HoneyWorks", facts, now))
    }

    @Test
    fun aRealReleaseIsNotMarked() {
        val facts = MusicParsers.videoFacts(Fixtures.json("video_facts_real"))
        assertEquals(624_317, facts.viewCount)
        assertEquals(listOf("shito", "Gom"), ReleaseSuspicion.credits(facts.description)!!.writers)
        assertEquals(emptyList(), ReleaseSuspicion.reasons("HoneyWorks", facts, now))
    }

    @Test
    fun selfWrittenAndOtherLabelsAreNotMarked() {
        // 名義がアーティスト名そのもの（自分で作詞・作曲）、レーベルが別（タイアップ）でも印は付けない
        val description =
            "Provided to YouTube by MusicRay'n Inc.\n\nアイのシナリオ · CHiCO with HoneyWorks\n\nアイのシナリオ\n\n℗ 2015 MusicRay'n Inc.\n\nReleased on: 2015-02-04\n\n" +
                "Composer, Lyricist, Arranger, Producer: HoneyWorks\nVocal: CHiCO\n\nAuto-generated by YouTube."
        val credits = ReleaseSuspicion.credits(description)!!
        assertEquals(listOf("HoneyWorks"), credits.writers)
        assertEquals(emptyList(), ReleaseSuspicion.reasons("HoneyWorks", VideoFacts(description, 50_000, null), now))
        // ボカロ曲（作曲者が名義に並び、作詞・作曲もその人）にも印は付けない
        val vocaloid = "Provided to YouTube by TuneCore Japan\n\nLove · Producer X · Hatsune Miku\n\nLove\n\nLyricist: Producer X\nComposer: Producer X\n\nAuto-generated by YouTube."
        assertEquals(emptyList(), ReleaseSuspicion.reasons("Hatsune Miku", VideoFacts(vocaloid, 5_000, null), now))
        // 自動でない説明文（MV など）は名義を読まない
        assertNull(ReleaseSuspicion.credits("2022年10月26日発売\nMusic&Lyrics：HoneyWorks"))
        // 出たばかりで再生が少ないのは怪しまない
        assertEquals(emptyList(), ReleaseSuspicion.reasons("HoneyWorks", VideoFacts(null, 3, "2026/10/30"), now))
    }

    @Test
    fun suspicionIsRememberedPerRelease() {
        val state =
            ReleaseWatchState(
                recent =
                    listOf(
                        NewRelease("UC1", "A", "x", "MP1", null, null),
                        NewRelease("UC1", "A", "y", "MP2", null, null, suspect = emptyList()),
                        NewRelease("UC1", "A", "v", null, "v1", null),
                    ),
            )
        assertEquals(listOf("MP1"), state.unchecked().map { it.albumBrowseId })
        val next = state.withSuspicion("MP1", listOf(ReleaseSuspicion.NAME))
        assertEquals(emptyList(), next.unchecked())
        assertEquals(listOf(ReleaseSuspicion.NAME), next.recent.first().suspect)
        assertEquals(next, ReleaseWatchState.decode(ReleaseWatchState.encode(next)))
    }
}

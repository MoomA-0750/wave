using Wave.Core.Music;
using Xunit;

namespace Wave.Core.Tests;

public class ReleaseSuspicionTests
{
    /// <summary>2026-11-02 の時刻。</summary>
    private static readonly long Now = ReleaseSuspicion.EpochDay("2026-11-02")!.Value * 24 * 60 * 60 * 1000;

    [Fact]
    public void AReleaseUnderAFakeNameIsMarked()
    {
        // HoneyWorks のページに混ざった別人の曲（名義は HoneyWorks OFFICIAL、作詞・作曲も同じ名義、3か月で再生3回。Android と同じ）
        var facts = MusicParsers.VideoFacts(Fixtures.Json("video_facts_suspect"));
        Assert.Equal(3, facts.ViewCount);
        var credits = ReleaseSuspicion.Credits(facts.Description)!;
        Assert.Equal("B-Komachi", credits.Label);
        Assert.Equal(["HoneyWorks OFFICIAL", "Han Shika"], credits.Artists);
        Assert.Equal(["HoneyWorks OFFICIAL"], credits.Writers);
        Assert.Equal("2026-07-28", credits.ReleasedOn);
        Assert.Equal([ReleaseSuspicion.Name, ReleaseSuspicion.Writer, ReleaseSuspicion.Views], ReleaseSuspicion.Reasons("HoneyWorks", facts, Now));
    }

    [Fact]
    public void ARealReleaseIsNotMarked()
    {
        var facts = MusicParsers.VideoFacts(Fixtures.Json("video_facts_real"));
        Assert.Equal(624_317, facts.ViewCount);
        Assert.Equal(["shito", "Gom"], ReleaseSuspicion.Credits(facts.Description)!.Writers);
        Assert.Empty(ReleaseSuspicion.Reasons("HoneyWorks", facts, Now));
    }

    [Fact]
    public void SelfWrittenAndOtherLabelsAreNotMarked()
    {
        // 名義がアーティスト名そのもの（自分で作詞・作曲）、レーベルが別（タイアップ）でも印は付けない
        var description =
            "Provided to YouTube by MusicRay'n Inc.\n\nアイのシナリオ · CHiCO with HoneyWorks\n\nアイのシナリオ\n\n℗ 2015 MusicRay'n Inc.\n\nReleased on: 2015-02-04\n\n" +
            "Composer, Lyricist, Arranger, Producer: HoneyWorks\nVocal: CHiCO\n\nAuto-generated by YouTube.";
        Assert.Equal(["HoneyWorks"], ReleaseSuspicion.Credits(description)!.Writers);
        Assert.Empty(ReleaseSuspicion.Reasons("HoneyWorks", new VideoFacts(description, 50_000, null), Now));
        // 自動でない説明文（MV など）は名義を読まない
        Assert.Null(ReleaseSuspicion.Credits("2022年10月26日発売\nMusic&Lyrics：HoneyWorks"));
        // 出たばかりで再生が少ないのは怪しまない
        Assert.Empty(ReleaseSuspicion.Reasons("HoneyWorks", new VideoFacts(null, 3, "2026/10/30"), Now));
    }

    [Fact]
    public void SuspicionIsRememberedPerRelease()
    {
        var state = ReleaseWatchState.Empty with
        {
            Recent =
            [
                new NewRelease("UC1", "A", "x", "MP1", null, null),
                new NewRelease("UC1", "A", "y", "MP2", null, null, Suspect: []),
                new NewRelease("UC1", "A", "v", null, "v1", null),
            ],
        };
        Assert.Equal(["MP1"], state.Unchecked().Select(r => r.AlbumBrowseId));
        var next = state.WithSuspicion("MP1", [ReleaseSuspicion.Name]);
        Assert.Empty(next.Unchecked());
        Assert.True(next.Recent[0].IsSuspect);
        // 保存して読み直しても印が残る（前の形の記録は未確認として読む）
        var decoded = ReleaseWatchState.Decode(next.Encode())!;
        Assert.Equal([ReleaseSuspicion.Name], decoded.Recent[0].Suspect);
        Assert.Empty(decoded.Recent[1].Suspect!);
        Assert.Null(ReleaseWatchState.Decode("""{"Seen":{},"Recent":[{"ArtistId":"UC1","ArtistName":"A","Title":"x","AlbumBrowseId":"MP1"}]}""")!.Recent[0].Suspect);
    }
}

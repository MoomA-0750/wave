using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;

namespace Wave.Core.Music;

/// <summary>YouTube（www.youtube.com）の動画のページから読んだ、新作の確かめに使う値（Android の VideoFacts と同じ）。</summary>
/// <param name="Description">説明文（配信元から来た曲は「Provided to YouTube by …」で始まる自動の説明文）。</param>
/// <param name="PublishedText">公開日（<c>2026/07/27</c> など、表示のまま）。</param>
public sealed record VideoFacts(string? Description, long? ViewCount, string? PublishedText);

/// <summary>自動の説明文（Provided to YouTube by …）の中身。Artists は2段目の「題名 · アーティスト · …」と Main Artist の欄、Writers は Lyricist・Composer・Writer の欄。</summary>
public sealed record ReleaseCredits(string? Label, List<string> Artists, List<string> Writers, string? ReleasedOn);

/// <summary>
/// 新作の出元が怪しいかの判定（印を付けて残す。外さない。Android の ReleaseSuspicion と同じ）。
/// 第三者が有名アーティストの名前で無関係の曲を配信し、YouTube がそのアーティストのページにまとめることがある（2026-11 の HoneyWorks の
/// 「Echoes for Peace」。名義は「HoneyWorks OFFICIAL」、作詞・作曲も同じ名義、公開から3か月で再生3回）。
/// 本物でもレーベルは作品ごとにばらばら（タイアップ・コラボ）なので、レーベルの違いでは判定しない。
/// </summary>
public static class ReleaseSuspicion
{
    /// <summary>名義がアーティスト名に「公式」などを足しただけのもの（なりすまし）。</summary>
    public const string Name = "name";

    /// <summary>作詞・作曲がアーティスト名でない名義そのまま（個人の名前が無い）。</summary>
    public const string Writer = "writer";

    /// <summary>公開から日が経っているのに、ほとんど再生されていない。</summary>
    public const string Views = "views";

    private const int MinViews = 100;
    private const int ViewsGraceDays = 14;
    private const long DayMs = 24L * 60 * 60 * 1000;
    private static readonly HashSet<string> NameSuffixes = ["official", "公式", "officialchannel", "channel"];
    private static readonly Regex DatePattern = new(@"(\d{4})[-/](\d{1,2})[-/](\d{1,2})");
    private const string Provided = "Provided to YouTube by ";

    public static ReleaseCredits? Credits(string? description)
    {
        var text = description?.Trim();
        if (text is null) return null;
        string? label = text.StartsWith(Provided, StringComparison.Ordinal) ? text.Split('\n')[0][Provided.Length..].Trim() : null;
        if (label is null && !text.Contains("Auto-generated by YouTube.", StringComparison.Ordinal)) return null;
        var paragraphs = text.Split("\n\n").Select(p => p.Trim()).ToList();
        var artists = new List<string>();
        // 2段目は「題名 · アーティスト · アーティスト」
        if (paragraphs.Count > 1) artists.AddRange(paragraphs[1].Split(" · ").Skip(1).Select(a => a.Trim()).Where(a => a.Length > 0));
        var writers = new List<string>();
        string? releasedOn = null;
        foreach (var line in text.Split('\n'))
        {
            var colon = line.IndexOf(": ", StringComparison.Ordinal);
            if (colon <= 0) continue;
            var keys = line[..colon].Split(',').Select(k => k.Trim()).ToList();
            var value = line[(colon + 2)..].Trim();
            if (value.Length == 0) continue;
            if (keys is ["Released on"]) releasedOn = value;
            else if (keys.Contains("Main Artist")) artists.Add(value);
            if (keys.Any(k => k is "Lyricist" or "Composer" or "Writer")) writers.Add(value);
        }
        return new ReleaseCredits(label, artists.Distinct().ToList(), writers.Distinct().ToList(), releasedOn);
    }

    /// <summary>怪しい点（無ければ空）。artistName はアーティストのページの名前。</summary>
    public static List<string> Reasons(string artistName, VideoFacts facts, long nowEpochMs)
    {
        var page = Key(artistName);
        var credits = Credits(facts.Description);
        var reasons = new List<string>();
        if (credits is not null)
        {
            var names = credits.Artists.Select(Key).ToList();
            if (names.Any(n => n != page && n.StartsWith(page, StringComparison.Ordinal) && NameSuffixes.Contains(n[page.Length..]))) reasons.Add(Name);
            var writers = credits.Writers.Select(Key).ToList();
            if (writers.Count > 0 && writers.All(w => names.Contains(w) && w != page)) reasons.Add(Writer);
        }
        var released = EpochDay(credits?.ReleasedOn) ?? EpochDay(facts.PublishedText);
        if (facts.ViewCount is { } views && views < MinViews && released is { } day && nowEpochMs / DayMs - day >= ViewsGraceDays) reasons.Add(Views);
        return reasons;
    }

    /// <summary>照らす形（大文字・小文字・全角・半角・空白を区別しない）。</summary>
    private static string Key(string name) =>
        new(name.Normalize(NormalizationForm.FormKC).ToLower(CultureInfo.InvariantCulture).Where(c => !char.IsWhiteSpace(c)).ToArray());

    /// <summary><c>2026-07-28</c>・<c>2026/07/27</c> の、1970-01-01 からの日数。</summary>
    public static long? EpochDay(string? text)
    {
        if (text is null || DatePattern.Match(text) is not { Success: true } m) return null;
        try
        {
            var date = new DateOnly(int.Parse(m.Groups[1].Value), int.Parse(m.Groups[2].Value), int.Parse(m.Groups[3].Value));
            return date.DayNumber - new DateOnly(1970, 1, 1).DayNumber;
        }
        catch (ArgumentOutOfRangeException)
        {
            return null;
        }
    }
}

import Foundation

/// YouTube（www.youtube.com）の動画のページから読んだ、新作の確かめに使う値（Android の VideoFacts と同じ）。
public struct VideoFacts: Equatable, Sendable {
    /// 説明文（配信元から来た曲は「Provided to YouTube by …」で始まる自動の説明文）。
    public var description: String?
    public var viewCount: Int64?
    /// 公開日（`2026/07/27` など、表示のまま）。
    public var publishedText: String?

    public init(description: String?, viewCount: Int64?, publishedText: String?) {
        self.description = description
        self.viewCount = viewCount
        self.publishedText = publishedText
    }
}

/// 自動の説明文（Provided to YouTube by …）の中身。
public struct ReleaseCredits: Equatable, Sendable {
    public var label: String?
    /// 2段目の「題名 · アーティスト · …」のアーティストと、Main Artist の欄。
    public var artists: [String]
    /// Lyricist・Composer・Writer の欄。
    public var writers: [String]
    /// Released on の日付（`2026-07-28`）。
    public var releasedOn: String?
}

/// 新作の出元が怪しいかの判定（印を付けて残す。外さない。Android の ReleaseSuspicion と同じ）。
/// 第三者が有名アーティストの名前で無関係の曲を配信し、YouTube がそのアーティストのページにまとめることがある。
/// 本物でもレーベルは作品ごとにばらばら（タイアップ・コラボ）なので、レーベルの違いでは判定しない。
public enum ReleaseSuspicion {
    /// 名義がアーティスト名に「公式」などを足しただけのもの（なりすまし）。
    public static let name = "name"
    /// 作詞・作曲が、アーティスト名を含むがアーティスト名ではない名義そのまま（個人の名前が無い）。
    public static let writer = "writer"
    /// 公開から日が経っているのに、ほとんど再生されていない。
    public static let views = "views"

    private static let minViews: Int64 = 100
    private static let viewsGraceDays: Int64 = 14
    private static let nameSuffixes: Set<String> = ["official", "公式", "officialchannel", "channel"]
    private static let provided = "Provided to YouTube by "

    public static func credits(_ description: String?) -> ReleaseCredits? {
        guard let text = description?.trimmingCharacters(in: .whitespacesAndNewlines) else { return nil }
        let first = text.split(separator: "\n", omittingEmptySubsequences: false).first.map(String.init) ?? ""
        let label = text.hasPrefix(provided) ? String(first.dropFirst(provided.count)).trimmingCharacters(in: .whitespaces) : nil
        if label == nil && !text.contains("Auto-generated by YouTube.") { return nil }
        let paragraphs = text.components(separatedBy: "\n\n").map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }
        var artists: [String] = []
        // 2段目は「題名 · アーティスト · アーティスト」
        if paragraphs.count > 1 {
            artists += paragraphs[1].components(separatedBy: " · ").dropFirst().map { $0.trimmingCharacters(in: .whitespaces) }.filter { !$0.isEmpty }
        }
        var writers: [String] = []
        var releasedOn: String?
        for line in text.components(separatedBy: "\n") {
            guard let colon = line.range(of: ": "), colon.lowerBound > line.startIndex else { continue }
            let keys = line[..<colon.lowerBound].split(separator: ",").map { $0.trimmingCharacters(in: .whitespaces) }
            let value = line[colon.upperBound...].trimmingCharacters(in: .whitespaces)
            if value.isEmpty { continue }
            if keys == ["Released on"] { releasedOn = value } else if keys.contains("Main Artist") { artists.append(value) }
            if keys.contains(where: { $0 == "Lyricist" || $0 == "Composer" || $0 == "Writer" }) { writers.append(value) }
        }
        return ReleaseCredits(label: label, artists: distinct(artists), writers: distinct(writers), releasedOn: releasedOn)
    }

    /// 怪しい点（無ければ空）。artistName はアーティストのページの名前。
    public static func reasons(artistName: String, facts: VideoFacts, nowEpochMs: Int64) -> [String] {
        let page = key(artistName)
        var reasons: [String] = []
        let credits = credits(facts.description)
        if let credits {
            let names = credits.artists.map(key)
            if names.contains(where: { $0 != page && $0.hasPrefix(page) && nameSuffixes.contains(String($0.dropFirst(page.count))) }) { reasons.append(ReleaseSuspicion.name) }
            let writers = credits.writers.map(key)
            if !writers.isEmpty && writers.allSatisfy({ names.contains($0) && $0 != page && $0.contains(page) }) { reasons.append(ReleaseSuspicion.writer) }
        }
        if let count = facts.viewCount, count < minViews, let released = epochDay(credits?.releasedOn) ?? epochDay(facts.publishedText),
           nowEpochMs / dayMs - released >= viewsGraceDays
        {
            reasons.append(ReleaseSuspicion.views)
        }
        return reasons
    }

    private static let dayMs: Int64 = 24 * 60 * 60 * 1000

    /// 照らす形（大文字・小文字・全角・半角・空白を区別しない）。
    private static func key(_ name: String) -> String {
        name.folding(options: [.caseInsensitive, .widthInsensitive], locale: nil).lowercased().filter { !$0.isWhitespace }
    }

    private static func distinct(_ list: [String]) -> [String] {
        var seen = Set<String>()
        return list.filter { seen.insert($0).inserted }
    }

    private static let datePattern = try! NSRegularExpression(pattern: #"(\d{4})[-/](\d{1,2})[-/](\d{1,2})"#)

    /// `2026-07-28`・`2026/07/27` の、1970-01-01 からの日数。
    public static func epochDay(_ text: String?) -> Int64? {
        guard let text else { return nil }
        let ns = text as NSString
        guard let m = datePattern.firstMatch(in: text, range: NSRange(location: 0, length: ns.length)),
              let y0 = Int64(ns.substring(with: m.range(at: 1))), let mo = Int64(ns.substring(with: m.range(at: 2))),
              let d = Int64(ns.substring(with: m.range(at: 3)))
        else { return nil }
        // 暦の日付から日数へ（Howard Hinnant の days_from_civil）
        let y = mo <= 2 ? y0 - 1 : y0
        let era = (y >= 0 ? y : y - 399) / 400
        let yoe = y - era * 400
        let doy = (153 * (mo + (mo > 2 ? -3 : 9)) + 2) / 5 + d - 1
        let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy
        return era * 146_097 + doe - 719_468
    }
}

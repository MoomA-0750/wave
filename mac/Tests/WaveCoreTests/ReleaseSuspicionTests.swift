import XCTest
@testable import WaveCore

/// 出元が怪しい新作の判定。Android の ReleaseSuspicionTest と同じ fixture・同じ期待値。
final class ReleaseSuspicionTests: XCTestCase {
    /// 2026-11-02 の時刻。
    private let now = ReleaseSuspicion.epochDay("2026-11-02")! * 24 * 60 * 60 * 1000

    func testAReleaseUnderAFakeNameIsMarked() {
        // HoneyWorks のページに混ざった別人の曲（名義は HoneyWorks OFFICIAL、作詞・作曲も同じ名義、3か月で再生3回）
        let facts = MusicParsers.videoFacts(Fixtures.json("video_facts_suspect"))
        XCTAssertEqual(3, facts.viewCount)
        let credits = ReleaseSuspicion.credits(facts.description)!
        XCTAssertEqual("B-Komachi", credits.label)
        XCTAssertEqual(["HoneyWorks OFFICIAL", "Han Shika"], credits.artists)
        XCTAssertEqual(["HoneyWorks OFFICIAL"], credits.writers)
        XCTAssertEqual("2026-07-28", credits.releasedOn)
        XCTAssertEqual([ReleaseSuspicion.name, ReleaseSuspicion.writer, ReleaseSuspicion.views],
                       ReleaseSuspicion.reasons(artistName: "HoneyWorks", facts: facts, nowEpochMs: now))
    }

    func testARealReleaseIsNotMarked() {
        let facts = MusicParsers.videoFacts(Fixtures.json("video_facts_real"))
        XCTAssertEqual(624_317, facts.viewCount)
        XCTAssertEqual(["shito", "Gom"], ReleaseSuspicion.credits(facts.description)!.writers)
        XCTAssertEqual([], ReleaseSuspicion.reasons(artistName: "HoneyWorks", facts: facts, nowEpochMs: now))
    }

    func testSelfWrittenAndOtherLabelsAreNotMarked() {
        // 名義がアーティスト名そのもの（自分で作詞・作曲）、レーベルが別（タイアップ）でも印は付けない
        let description = "Provided to YouTube by MusicRay'n Inc.\n\nアイのシナリオ · CHiCO with HoneyWorks\n\nアイのシナリオ\n\n℗ 2015 MusicRay'n Inc.\n\nReleased on: 2015-02-04\n\n"
            + "Composer, Lyricist, Arranger, Producer: HoneyWorks\nVocal: CHiCO\n\nAuto-generated by YouTube."
        XCTAssertEqual(["HoneyWorks"], ReleaseSuspicion.credits(description)!.writers)
        XCTAssertEqual([], ReleaseSuspicion.reasons(artistName: "HoneyWorks", facts: VideoFacts(description: description, viewCount: 50000, publishedText: nil), nowEpochMs: now))
        // ボカロ曲（作曲者が名義に並び、作詞・作曲もその人）にも印は付けない
        let vocaloid = "Provided to YouTube by TuneCore Japan\n\nLove · Producer X · Hatsune Miku\n\nLove\n\nLyricist: Producer X\nComposer: Producer X\n\nAuto-generated by YouTube."
        XCTAssertEqual([], ReleaseSuspicion.reasons(artistName: "Hatsune Miku", facts: VideoFacts(description: vocaloid, viewCount: 5000, publishedText: nil), nowEpochMs: now))
        // 自動でない説明文（MV など）は名義を読まない
        XCTAssertNil(ReleaseSuspicion.credits("2022年10月26日発売\nMusic&Lyrics：HoneyWorks"))
        // 出たばかりで再生が少ないのは怪しまない
        XCTAssertEqual([], ReleaseSuspicion.reasons(artistName: "HoneyWorks", facts: VideoFacts(description: nil, viewCount: 3, publishedText: "2026/10/30"), nowEpochMs: now))
    }

    func testSuspicionIsRememberedPerRelease() {
        let state = ReleaseWatchState(seen: [:], recent: [
            NewRelease(artistId: "UC1", artistName: "A", title: "x", albumBrowseId: "MP1", videoId: nil, thumbnailUrl: nil),
            NewRelease(artistId: "UC1", artistName: "A", title: "y", albumBrowseId: "MP2", videoId: nil, thumbnailUrl: nil, suspect: []),
            NewRelease(artistId: "UC1", artistName: "A", title: "v", albumBrowseId: nil, videoId: "v1", thumbnailUrl: nil),
        ])
        XCTAssertEqual(["MP1"], state.unchecked().map(\.albumBrowseId))
        let next = state.withSuspicion("MP1", reasons: [ReleaseSuspicion.name])
        XCTAssertTrue(next.unchecked().isEmpty)
        XCTAssertEqual([ReleaseSuspicion.name], next.recent.first?.suspect)
        XCTAssertTrue(next.recent.first!.isSuspect)
        XCTAssertEqual(next, ReleaseWatchState.decode(next.encode()))
    }
}

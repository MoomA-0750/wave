//! 新作の出元が怪しいかの判定（印を付けて残す。外さない。Android の ReleaseSuspicion と同じ）。
//! 第三者が有名アーティストの名前で無関係の曲を配信し、YouTube がそのアーティストのページにまとめることがある（2026-11 の HoneyWorks の
//! 「Echoes for Peace」。名義は「HoneyWorks OFFICIAL」、作詞・作曲も同じ名義、公開から3か月で再生3回）。
//! 本物でもレーベルは作品ごとにばらばら（タイアップ・コラボ）なので、レーベルの違いでは判定しない。

use std::sync::LazyLock;

use regex::Regex;
use serde_json::Value;

use crate::lyrics::search::normalize;

/// 名義がアーティスト名に「公式」などを足しただけのもの（なりすまし）。
pub const NAME: &str = "name";
/// 作詞・作曲がアーティスト名でない名義そのまま（個人の名前が無い）。
pub const WRITER: &str = "writer";
/// 公開から日が経っているのに、ほとんど再生されていない。
pub const VIEWS: &str = "views";

const MIN_VIEWS: u64 = 100;
const VIEWS_GRACE_DAYS: i64 = 14;
const NAME_SUFFIXES: [&str; 4] = ["official", "公式", "officialchannel", "channel"];
const DAY_MS: i64 = 24 * 60 * 60 * 1000;

static DATE: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"(\d{4})[-/](\d{1,2})[-/](\d{1,2})").expect("valid regex"));

/// YouTube（www.youtube.com）の動画のページから読んだ、新作の確かめに使う値。
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct VideoFacts {
    /// 説明文（配信元から来た曲は「Provided to YouTube by …」で始まる自動の説明文）。
    pub description: Option<String>,
    pub view_count: Option<u64>,
    /// 公開日（`2026/07/27` など、表示のまま）。
    pub published_text: Option<String>,
}

/// 自動の説明文（Provided to YouTube by …）の中身。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ReleaseCredits {
    pub label: Option<String>,
    /// 2段目の「題名 · アーティスト · …」のアーティストと、Main Artist の欄。
    pub artists: Vec<String>,
    /// Lyricist・Composer・Writer の欄。
    pub writers: Vec<String>,
    /// Released on の日付（`2026-07-28`）。
    pub released_on: Option<String>,
}

fn find_first<'a>(value: &'a Value, key: &str) -> Option<&'a Value> {
    match value {
        Value::Object(map) => map.get(key).or_else(|| map.values().find_map(|v| find_first(v, key))),
        Value::Array(items) => items.iter().find_map(|v| find_first(v, key)),
        _ => None,
    }
}

/// YouTube の動画のページ（WEB の next）から、説明文・再生回数・公開日を読む。
pub fn video_facts(root: &Value) -> VideoFacts {
    let primary = find_first(root, "videoPrimaryInfoRenderer");
    let secondary = find_first(root, "videoSecondaryInfoRenderer");
    let views = primary.and_then(|p| p.pointer("/viewCount/videoViewCountRenderer/viewCount/simpleText")).and_then(Value::as_str);
    VideoFacts {
        description: secondary.and_then(|s| s.pointer("/attributedDescription/content")).and_then(Value::as_str).map(str::to_string),
        view_count: views.map(|v| v.chars().filter(char::is_ascii_digit).collect::<String>()).and_then(|d| d.parse().ok()),
        published_text: primary.and_then(|p| p.pointer("/dateText/simpleText")).and_then(Value::as_str).map(str::to_string),
    }
}

fn push_unique(list: &mut Vec<String>, value: String) {
    if !list.contains(&value) {
        list.push(value);
    }
}

pub fn credits(description: Option<&str>) -> Option<ReleaseCredits> {
    let text = description?.trim();
    let label = text.strip_prefix("Provided to YouTube by ").and_then(|rest| rest.lines().next()).map(|l| l.trim().to_string());
    if label.is_none() && !text.contains("Auto-generated by YouTube.") {
        return None;
    }
    let mut artists = Vec::new();
    // 2段目は「題名 · アーティスト · アーティスト」
    if let Some(second) = text.split("\n\n").nth(1) {
        for name in second.trim().split(" · ").skip(1).map(str::trim).filter(|n| !n.is_empty()) {
            push_unique(&mut artists, name.to_string());
        }
    }
    let mut writers = Vec::new();
    let mut released_on = None;
    for line in text.lines() {
        let Some(colon) = line.find(": ").filter(|&c| c > 0) else { continue };
        let keys: Vec<&str> = line[..colon].split(',').map(str::trim).collect();
        let value = line[colon + 2..].trim();
        if value.is_empty() {
            continue;
        }
        if keys == ["Released on"] {
            released_on = Some(value.to_string());
        } else if keys.contains(&"Main Artist") {
            push_unique(&mut artists, value.to_string());
        }
        if keys.iter().any(|k| matches!(*k, "Lyricist" | "Composer" | "Writer")) {
            push_unique(&mut writers, value.to_string());
        }
    }
    Some(ReleaseCredits { label, artists, writers, released_on })
}

/// 怪しい点（無ければ空）。artist_name はアーティストのページの名前。
pub fn reasons(artist_name: &str, facts: &VideoFacts, now_epoch_ms: i64) -> Vec<String> {
    let page = normalize(artist_name);
    let credits = credits(facts.description.as_deref());
    let mut reasons = Vec::new();
    if let Some(credits) = &credits {
        let names: Vec<String> = credits.artists.iter().map(|n| normalize(n)).collect();
        if names.iter().any(|n| *n != page && n.strip_prefix(page.as_str()).is_some_and(|rest| NAME_SUFFIXES.contains(&rest))) {
            reasons.push(NAME.to_string());
        }
        let writers: Vec<String> = credits.writers.iter().map(|n| normalize(n)).collect();
        if !writers.is_empty() && writers.iter().all(|w| names.contains(w) && *w != page) {
            reasons.push(WRITER.to_string());
        }
    }
    let released = epoch_day(credits.as_ref().and_then(|c| c.released_on.as_deref())).or_else(|| epoch_day(facts.published_text.as_deref()));
    if let (Some(views), Some(released)) = (facts.view_count, released)
        && views < MIN_VIEWS
        && now_epoch_ms / DAY_MS - released >= VIEWS_GRACE_DAYS
    {
        reasons.push(VIEWS.to_string());
    }
    reasons
}

/// `2026-07-28`・`2026/07/27` の、1970-01-01 からの日数。
pub fn epoch_day(text: Option<&str>) -> Option<i64> {
    let caps = DATE.captures(text?)?;
    let (y0, m, d): (i64, i64, i64) = (caps[1].parse().ok()?, caps[2].parse().ok()?, caps[3].parse().ok()?);
    // 暦の日付から日数へ（Howard Hinnant の days_from_civil）
    let y = if m <= 2 { y0 - 1 } else { y0 };
    let era = if y >= 0 { y } else { y - 399 } / 400;
    let yoe = y - era * 400;
    let doy = (153 * (m + if m > 2 { -3 } else { 9 }) + 2) / 5 + d - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    Some(era * 146097 + doe - 719468)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn fixture(name: &str) -> Value {
        // 手本の応答は Android の core と共通（core/src/desktopTest/resources/fixtures）
        let path = format!("{}/../../core/src/desktopTest/resources/fixtures/{name}.json", env!("CARGO_MANIFEST_DIR"));
        serde_json::from_str(&std::fs::read_to_string(path).unwrap()).unwrap()
    }

    fn now() -> i64 {
        epoch_day(Some("2026-11-02")).unwrap() * DAY_MS
    }

    #[test]
    fn a_release_under_a_fake_name_is_marked() {
        // HoneyWorks のページに混ざった別人の曲（名義は HoneyWorks OFFICIAL、作詞・作曲も同じ名義、3か月で再生3回）
        let facts = video_facts(&fixture("video_facts_suspect"));
        assert_eq!(facts.view_count, Some(3));
        let credits = credits(facts.description.as_deref()).unwrap();
        assert_eq!(credits.label.as_deref(), Some("B-Komachi"));
        assert_eq!(credits.artists, ["HoneyWorks OFFICIAL", "Han Shika"]);
        assert_eq!(credits.writers, ["HoneyWorks OFFICIAL"]);
        assert_eq!(credits.released_on.as_deref(), Some("2026-07-28"));
        assert_eq!(reasons("HoneyWorks", &facts, now()), [NAME, WRITER, VIEWS]);
    }

    #[test]
    fn a_real_release_is_not_marked() {
        let facts = video_facts(&fixture("video_facts_real"));
        assert_eq!(facts.view_count, Some(624_317));
        assert_eq!(credits(facts.description.as_deref()).unwrap().writers, ["shito", "Gom"]);
        assert!(reasons("HoneyWorks", &facts, now()).is_empty());
    }

    #[test]
    fn self_written_and_other_labels_are_not_marked() {
        // 名義がアーティスト名そのもの（自分で作詞・作曲）、レーベルが別（タイアップ）でも印は付けない
        let description = "Provided to YouTube by MusicRay'n Inc.\n\nアイのシナリオ · CHiCO with HoneyWorks\n\nアイのシナリオ\n\n℗ 2015 MusicRay'n Inc.\n\nReleased on: 2015-02-04\n\nComposer, Lyricist, Arranger, Producer: HoneyWorks\nVocal: CHiCO\n\nAuto-generated by YouTube.";
        assert_eq!(credits(Some(description)).unwrap().writers, ["HoneyWorks"]);
        let facts = VideoFacts { description: Some(description.into()), view_count: Some(50_000), published_text: None };
        assert!(reasons("HoneyWorks", &facts, now()).is_empty());
        // 自動でない説明文（MV など）は名義を読まない
        assert!(credits(Some("2022年10月26日発売\nMusic&Lyrics：HoneyWorks")).is_none());
        // 出たばかりで再生が少ないのは怪しまない
        let fresh = VideoFacts { description: None, view_count: Some(3), published_text: Some("2026/10/30".into()) };
        assert!(reasons("HoneyWorks", &fresh, now()).is_empty());
    }
}
